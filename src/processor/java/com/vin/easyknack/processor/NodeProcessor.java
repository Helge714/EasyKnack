package com.vin.easyknack.processor;

import java.io.IOException;
import java.util.*;
import javax.annotation.processing.*;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.*;
import javax.tools.Diagnostic;

/** Bootstrapped by Maven before compiling the application; has no runtime dependencies. */
@SupportedAnnotationTypes("com.vin.easyknack.nodes.RegisterNode")
public final class NodeProcessor extends AbstractProcessor {
    private boolean generated;
    @Override public SourceVersion getSupportedSourceVersion() { return SourceVersion.latestSupported(); }
    @Override public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment round) {
        if (generated || round.processingOver() || annotations.isEmpty()) return false;
        var base = processingEnv.getElementUtils().getTypeElement("com.vin.easyknack.nodes.BasicNode");
        Map<String, String> types = new TreeMap<>();
        boolean invalid = false;
        List<Element> origins = new ArrayList<>();
        for (var annotation : annotations) for (var element : round.getElementsAnnotatedWith(annotation)) {
            origins.add(element);
            if (!(element instanceof TypeElement type) || element.getKind() != ElementKind.CLASS
                    || !element.getModifiers().contains(Modifier.PUBLIC) || element.getModifiers().contains(Modifier.ABSTRACT)
                    || !processingEnv.getTypeUtils().isSubtype(element.asType(), base.asType())
                    || type.getNestingKind() != NestingKind.TOP_LEVEL) {
                error(element, "@RegisterNode requires a public, concrete top-level BasicNode class"); invalid = true; continue;
            }
            boolean constructor = type.getEnclosedElements().stream().filter(e -> e.getKind() == ElementKind.CONSTRUCTOR)
                    .map(ExecutableElement.class::cast).anyMatch(e -> e.getParameters().isEmpty()
                            && e.getModifiers().contains(Modifier.PUBLIC) && e.getThrownTypes().isEmpty());
            if (!constructor) { error(element, "Node needs a public no-argument constructor without checked exceptions"); invalid = true; }
            String id = null;
            for (var mirror : element.getAnnotationMirrors()) if (mirror.getAnnotationType().asElement().equals(annotation))
                for (var value : processingEnv.getElementUtils().getElementValuesWithDefaults(mirror).entrySet())
                    if (value.getKey().getSimpleName().contentEquals("id")) id = value.getValue().getValue().toString();
            if (id == null || !id.matches("[a-z][a-z0-9]*(\\.[a-z][a-z0-9]*)+") || id.contains(".variant.")) {
                error(element, "Node ID must be a stable, qualified lowercase ID (without .variant.)"); invalid = true;
            } else if (types.putIfAbsent(id, type.getQualifiedName().toString()) != null) {
                error(element, "Duplicate node ID: " + id); invalid = true;
            }
        }
        generated = true;
        if (!invalid) try (var writer = processingEnv.getFiler().createSourceFile(
                "com.vin.easyknack.nodes.GeneratedNodes", origins.toArray(Element[]::new)).openWriter()) {
            writer.write("package com.vin.easyknack.nodes;\n// Generated by NodeProcessor. Do not edit.\n"
                    + "public final class GeneratedNodes { private GeneratedNodes() {}\n"
                    + "public static java.util.List<BasicNode> create() { return java.util.List.of(\n"
                    + String.join(",\n", types.values().stream().map(n -> "new " + n + "()").toList()) + "); }\n}\n");
        } catch (IOException failure) { error(null, "Cannot generate node registry: " + failure); }
        return true;
    }
    private void error(Element element, String message) { processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR, message, element); }
}
