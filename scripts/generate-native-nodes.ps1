param(
    [string]$NodeDirectory = (Join-Path (Split-Path -Parent $PSScriptRoot) 'native/audio-host/src/nodes'),
    [string]$OutputDirectory = (Join-Path (Split-Path -Parent $PSScriptRoot) 'target/native/generated')
)
$ErrorActionPreference = 'Stop'
New-Item -ItemType Directory -Force $OutputDirectory | Out-Null
$registrations = @()
$ids = @{}
foreach ($header in (Get-ChildItem -LiteralPath $NodeDirectory -Filter '*.hpp' -File -Recurse | Sort-Object FullName)) {
    $text = [IO.File]::ReadAllText($header.FullName)
    $declarations = [regex]::Matches($text, '(?m)^\s*EASYKNACK_NODE\(\s*([A-Za-z_][A-Za-z0-9_:]*)\s*,\s*"([a-z][a-z0-9_-]*)"\s*\)\s*$')
    foreach ($match in $declarations) {
        $type = $match.Groups[1].Value
        $id = $match.Groups[2].Value
        if ($ids.ContainsKey($id)) { throw "Duplicate native processor ID: $id" }
        $ids[$id] = $true
        $relative = $header.FullName.Substring((Get-Item -LiteralPath $NodeDirectory).FullName.Length + 1).Replace('\', '/')
        $registrations += [pscustomobject]@{ id = $id; type = $type; header = "nodes/$relative" }
    }
    if ([regex]::Matches($text, '(?m)^\s*EASYKNACK_NODE').Count -ne $declarations.Count) {
        throw "Malformed EASYKNACK_NODE in $($header.Name)"
    }
}
if ($registrations.Count -eq 0) { throw 'No native node registrations found' }
$lines = @('// Generated by generate-native-nodes.ps1. Do not edit.', '#pragma once', '#include <memory>', '#include <string>', '#include <stdexcept>')
foreach ($header in ($registrations.header | Select-Object -Unique)) { $lines += '#include "' + $header + '"' }
$lines += 'namespace easyknack {', 'inline std::unique_ptr<NodeProcessor> createNodeProcessor(const std::string& id) {'
foreach ($registration in $registrations) {
    $lines += '    if (id == "' + $registration.id + '") return std::make_unique<' + $registration.type + '>();'
}
$lines += '    throw std::runtime_error("unknown node type: " + id);', '}', '}'
function Write-IfChanged([string]$Path, [string]$Content) {
    if (![IO.File]::Exists($Path) -or [IO.File]::ReadAllText($Path) -cne $Content) {
        [IO.File]::WriteAllText($Path, $Content, [Text.UTF8Encoding]::new($false))
    }
}
Write-IfChanged (Join-Path $OutputDirectory 'GeneratedNodeRegistry.hpp') (($lines -join "`n") + "`n")
Write-IfChanged (Join-Path $OutputDirectory 'nodes.json') (ConvertTo-Json -InputObject @($registrations))
