#Requires -Version 7.0
$ErrorActionPreference = 'Stop'
. "$PSScriptRoot/SourcePackage.ps1"
$root = Split-Path -Parent $PSScriptRoot
$work = Join-Path $root "target/source-package-tests/$([guid]::NewGuid().ToString('N'))"
New-Item -ItemType Directory -Force -Path "$work/src", "$work/.settings" | Out-Null
& git -C $work init -q
if ($LASTEXITCODE -ne 0) { throw 'Cannot initialize test repository.' }
Set-Content -LiteralPath "$work/src/Änderung.java" -Value 'original' -Encoding utf8
Set-Content -LiteralPath "$work/.settings/local.xml" -Value 'must not be included'
Set-Content -LiteralPath "$work/src/private.key" -Value 'must not be included'
$snapshot = Get-SourceSnapshot $work
if ($snapshot.Count -ne 1 -or $snapshot[0].path -cne 'src/Änderung.java') { throw 'Source enumeration or exclusion failed.' }
$entries = [ordered]@{'source.txt'="$work/src/Änderung.java"; 'metadata.json'=[Text.Encoding]::UTF8.GetBytes('{}')}
Write-DeterministicZip "$work/a.zip" $entries
Write-DeterministicZip "$work/b.zip" $entries
if ((Get-FileHash "$work/a.zip").Hash -cne (Get-FileHash "$work/b.zip").Hash) { throw 'Archive is not deterministic.' }
$rejected = $false
try { Write-DeterministicZip "$work/a.zip" $entries } catch { $rejected = $true }
if (!$rejected) { throw 'Existing archive was replaced.' }
$rejected = $false
try { Write-DeterministicZip "$work/unsafe.zip" @{'../escape'=[byte[]]@(1)} } catch { $rejected = $true }
if (!$rejected) { throw 'Unsafe entry was accepted.' }
Assert-SourceSnapshot $work $snapshot
Set-Content -LiteralPath "$work/src/Änderung.java" -Value 'changed'
$rejected = $false
try { Assert-SourceSnapshot $work $snapshot } catch { $rejected = $true }
if (!$rejected) { throw 'Source mutation was missed.' }
New-Item -ItemType Directory -Force -Path "$work/compiler/python/__pycache__", "$work/staged" | Out-Null
Set-Content "$work/compiler/python/__pycache__/example.pyc" 'generated bytecode'
Set-Content "$work/compiler/python/example.py" 'original Python source'
Set-Content "$work/compiler/python/standalone.pyc" 'potential bytecode-only module'
Copy-Item -LiteralPath "$work/compiler" -Destination "$work/staged/compiler" -Recurse
Remove-CompilerBytecodeCaches "$work/staged/compiler"
if (Test-Path "$work/staged/compiler/python/__pycache__/example.pyc") { throw 'Staged bytecode cache survived.' }
if (!(Test-Path "$work/compiler/python/__pycache__/example.pyc")) { throw 'Original compiler was changed.' }
if (!(Test-Path "$work/staged/compiler/python/example.py")) { throw 'Python source was removed.' }
if (!(Test-Path "$work/staged/compiler/python/standalone.pyc")) { throw 'Non-cache Python module was removed.' }
Write-Host 'Source-package tests passed: deterministic bytes, Unicode paths, exclusions, no overwrite, no traversal, source mutation detection.'
Write-Host 'Compiler cache cleanup passed: only staged bytecode removed; original toolchain and Python sources preserved.'
# Fast packaging traversal must retain Unicode paths and byte/hash identity.
$fastSource = "$work/fast-source"; $fastDestination = "$work/fast-copy"
New-Item -ItemType Directory -Path "$fastSource/empty", "$fastSource/ä" -Force | Out-Null
[IO.File]::WriteAllBytes("$fastSource/ä/data.bin", [byte[]](0,1,127,255))
[EasyKnackPackageFiles]::CopyTree($fastSource,$fastDestination)
if (!(Test-Path -LiteralPath "$fastDestination/empty" -PathType Container)) { throw 'Empty directory was lost.' }
$inventory = [EasyKnackPackageFiles]::Inventory($fastDestination)
if ($inventory.Count -ne 1 -or $inventory[0].bytes -ne 4) { throw 'Inventory shape mismatch.' }
if ($inventory[0].sha256 -ne (Get-FileHash -LiteralPath "$fastSource/ä/data.bin" -Algorithm SHA256).Hash) { throw 'Inventory checksum mismatch.' }
$rejected=$false;try {[EasyKnackPackageFiles]::CopyTree($fastSource,$fastDestination)}catch{$rejected=$true}
if (!$rejected) { throw 'Copy overwrote an existing destination.' }
$rejected=$false;try {[EasyKnackPackageFiles]::CopyTree($fastSource,"$fastSource/nested")}catch{$rejected=$true}
if (!$rejected) { throw 'Copy accepted a recursive destination.' }
Write-Host 'Fast tree copy and inventory passed: Unicode, empty directories, exact hashes and no overwrite.'
